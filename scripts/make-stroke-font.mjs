/**
 * Turns an EMS SVG stroke font into lib/fonts/allure.ts (plain polylines, no runtime SVG parsing).
 *
 *   node scripts/make-stroke-font.mjs path/to/EMSAllure.svg
 *
 * Source: https://gitlab.com/oskay/svg-fonts (EMS Allure, SIL Open Font License; see lib/fonts/EMS-Allure-OFL.txt).
 * Curves are flattened to short straight segments; coordinates are rounded to whole font units.
 */
import fs from "node:fs";
import path from "node:path";

const source = process.argv[2];
if (!source) {
  console.error("usage: node scripts/make-stroke-font.mjs <EMSAllure.svg>");
  process.exit(1);
}
const svg = fs.readFileSync(source, "utf8");
const num = (re) => Number(svg.match(re)?.[1]);
const unitsPerEm = num(/units-per-em="([\d.]+)"/);
const ascent = num(/ascent="([\d.]+)"/);
const descent = num(/descent="(-?[\d.]+)"/);
const defaultAdv = num(/<font [^>]*horiz-adv-x="([\d.]+)"/);

const decode = (s) =>
  s
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">");

const cubic = (p0, p1, p2, p3, steps) => {
  const out = [];
  for (let i = 1; i <= steps; i++) {
    const t = i / steps;
    const u = 1 - t;
    out.push([
      u * u * u * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t * t * t * p3[0],
      u * u * u * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t * t * t * p3[1],
    ]);
  }
  return out;
};

/** "M x y L x y C x1 y1 x2 y2 x y" into a list of polylines (one per pen-down stroke). */
function strokesOf(d) {
  const tokens = d.match(/[MLC]|-?\d*\.?\d+(?:e-?\d+)?/gi) ?? [];
  const strokes = [];
  let current = null;
  let cmd = "";
  let at = [0, 0];
  let i = 0;
  const read = () => Number(tokens[i++]);
  while (i < tokens.length) {
    if (/[MLC]/i.test(tokens[i])) cmd = tokens[i++].toUpperCase();
    if (cmd === "M") {
      at = [read(), read()];
      current = [at];
      strokes.push(current);
    } else if (cmd === "L") {
      at = [read(), read()];
      current.push(at);
    } else if (cmd === "C") {
      const p1 = [read(), read()];
      const p2 = [read(), read()];
      const p3 = [read(), read()];
      current.push(...cubic(at, p1, p2, p3, 8));
      at = p3;
    }
  }
  return strokes.filter((s) => s.length > 1);
}

const glyphs = {};
for (const m of svg.matchAll(/<glyph\s+([^>]*?)\/>/g)) {
  const attrs = Object.fromEntries([...m[1].matchAll(/([\w-]+)="([^"]*)"/g)].map((a) => [a[1], a[2]]));
  if (attrs.unicode === undefined) continue;
  const ch = decode(attrs.unicode);
  if ([...ch].length !== 1) continue;
  const code = ch.codePointAt(0);
  if (code > 0x17f && ![0x2018, 0x2019, 0x201c, 0x201d, 0x2013, 0x2014, 0x2026].includes(code)) continue;
  const strokes = attrs.d ? strokesOf(attrs.d).map((s) => s.flatMap(([x, y]) => [Math.round(x), Math.round(y)])) : [];
  glyphs[ch] = { adv: Math.round(Number(attrs["horiz-adv-x"] ?? defaultAdv)), strokes };
}

const lines = Object.entries(glyphs).map(
  ([ch, g]) => `  ${JSON.stringify(ch)}: { adv: ${g.adv}, strokes: ${JSON.stringify(g.strokes)} },`,
);
const out = `// Generated by scripts/make-stroke-font.mjs from EMS Allure. Do not edit by hand.
// EMS Allure is a derivative of Allura (Rob Leuschke, TypeSETit), SIL Open Font License 1.1: see EMS-Allure-OFL.txt.
import type { StrokeFont } from "@/lib/write-on";

export const ALLURE: StrokeFont = {
  unitsPerEm: ${unitsPerEm},
  ascent: ${ascent},
  descent: ${descent},
  glyphs: {
${lines.join("\n")}
  },
};
`;
const target = path.join(import.meta.dirname, "..", "lib", "fonts", "allure.ts");
fs.writeFileSync(target, out);
console.log(`${Object.keys(glyphs).length} glyphs, ${(out.length / 1024).toFixed(0)} KB -> ${target}`);
